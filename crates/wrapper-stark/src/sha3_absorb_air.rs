        assert_eq!(Sha3Variant::Sha3_256.output_bytes(), 32);
        assert_eq!(Sha3Variant::Sha3_256.block_bytes(),  136);

        assert_eq!(Sha3Variant::Sha3_384.rate_bits(),   832);
        assert_eq!(Sha3Variant::Sha3_384.capacity_bits(), 768);
