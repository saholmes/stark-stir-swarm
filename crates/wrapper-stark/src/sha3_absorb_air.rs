#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sha3_variant_sponge_invariant() {
        for v in [Sha3Variant::Sha3_256, Sha3Variant::Sha3_384, Sha3Variant::Sha3_512] {
            // FIPS 202 sponge invariant: r + c = 1600.
            assert_eq!(v.rate_bits() + v.capacity_bits(), 1600);
            // Output ≤ rate (otherwise extra squeeze rounds needed).
            assert!(v.output_bits() <= v.rate_bits());
            // Block size is byte-aligned.
            assert_eq!(v.rate_bits() % 8, 0);
        }
    }

    #[test]
    fn sha3_variant_specific_values() {
        // FIPS 202 §6.1 Table 3.
        assert_eq!(Sha3Variant::Sha3_256.rate_bits(),  1088);
        assert_eq!(Sha3Variant::Sha3_256.capacity_bits(), 512);
        assert_eq!(Sha3Variant::Sha3_256.output_bytes(), 32);
        assert_eq!(Sha3Variant::Sha3_256.block_bytes(),  136);

        assert_eq!(Sha3Variant::Sha3_384.rate_bits(),   832);
        assert_eq!(Sha3Variant::Sha3_384.capacity_bits(), 768);
        assert_eq!(Sha3Variant::Sha3_384.output_bytes(), 48);
        assert_eq!(Sha3Variant::Sha3_384.block_bytes(),  104);

        assert_eq!(Sha3Variant::Sha3_512.rate_bits(),   576);
        assert_eq!(Sha3Variant::Sha3_512.capacity_bits(), 1024);
        assert_eq!(Sha3Variant::Sha3_512.output_bytes(), 64);
        assert_eq!(Sha3Variant::Sha3_512.block_bytes(),  72);
    }

    #[test]
    fn sha3_variant_default_for_level() {
        assert_eq!(Sha3Variant::default_for_level(1), Sha3Variant::Sha3_256);
        assert_eq!(Sha3Variant::default_for_level(3), Sha3Variant::Sha3_384);
        assert_eq!(Sha3Variant::default_for_level(5), Sha3Variant::Sha3_512);
    }

    #[test]
    fn round_constants_count_and_shape() {
        assert_eq!(ROUND_CONSTANTS.len(), 24);
        // First constant must be 1 (lowest LFSR output before stepping).
        assert_eq!(ROUND_CONSTANTS[0], 0x0000_0000_0000_0001);
        // ι output must fit in 64 bits — vacuous for u64 but confirms type.
        for rc in ROUND_CONSTANTS {
            assert!(rc <= u64::MAX);
        }
    }

    #[test]
    fn rho_offsets_well_formed() {
        // FIPS 202 §3.2.2 Table 1: exactly one offset is 0 (lane (0, 0));
        // remaining 24 offsets are distinct mod 64.
        assert_eq!(RHO_OFFSETS.len(), 25);
        assert_eq!(RHO_OFFSETS[0], 0);
        let mut nonzero: Vec<u32> = RHO_OFFSETS.iter().filter(|&&o| o != 0).copied().collect();
        nonzero.sort();
        nonzero.dedup();
        assert_eq!(nonzero.len(), 24, "ρ offsets must be 24 distinct non-zero values");
        // All offsets are < 64.
        assert!(RHO_OFFSETS.iter().all(|&o| o < 64));
    }

    #[test]
    fn pi_lane_indices_is_permutation() {
        // π is a permutation of {0..25}.
        assert_eq!(PI_LANE_INDICES.len(), 25);
        let mut sorted: Vec<usize> = PI_LANE_INDICES.to_vec();
        sorted.sort();
        for i in 0..25 {
            assert_eq!(sorted[i], i, "PI_LANE_INDICES is not a permutation");
        }
    }

    #[test]
    fn round_step_count() {
        assert_eq!(RoundStep::ALL.len(), 5);
    }

    #[test]
    fn absorb_layout_row_budget() {
        let l = AbsorbAirLayout::new(Sha3Variant::Sha3_384, 4);
        assert_eq!(l.rows_per_permutation, 120);  // 24 × 5
        assert_eq!(l.rows_per_absorb_block, 121); // 120 + XOR row
        assert_eq!(l.total_rows(), 121 * 4);
        // Width sanity: 1600 state bits + 4×25 helper lanes + 1 RC + 5 selectors.
        assert_eq!(l.width, 1600 + 100 + 1 + 5);
    }

    #[test]
    fn absorb_layout_scales_linearly_with_blocks() {
        let l1 = AbsorbAirLayout::new(Sha3Variant::Sha3_256, 1);
        let l4 = AbsorbAirLayout::new(Sha3Variant::Sha3_256, 4);
        assert_eq!(l4.total_rows(), 4 * l1.total_rows());
        // Width is independent of block count.
        assert_eq!(l4.width, l1.width);
    }

    #[test]
    #[should_panic(expected = "not yet wired")]
    fn keccak_f1600_stub_panics() {
        let mut s: KeccakState = [0; 25];
        keccak_f1600(&mut s);
    }

    #[test]
    #[should_panic(expected = "unsupported NIST level")]
    fn sha3_variant_rejects_invalid_level() {
        let _ = Sha3Variant::default_for_level(2);
    }
}
