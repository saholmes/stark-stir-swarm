//! SHA-3 (Keccak-f1600) absorb-sequence AIR.
//!
//! # Purpose
//!
//! The wrapper STARK has to verify the inner proof's Merkle paths and
//! re-derive its `pi_hash` Fiat-Shamir transcript.  Those operations
//! commit to SHA-3 hashes, so the wrapper AIR contains a SHA-3 sub-AIR.
//! This is the only place SHA-3-in-AIR is unavoidable; the dual-hash
//! architecture (paper §8) limits it to this subcircuit while the
//! wrapper's own internal Merkle uses Poseidon (cheap to express).
//!
//! # Keccak-f1600 structure (FIPS 202 §3)
//!
//! - **State**: 5×5×64 = 1 600 bits arranged as 25 64-bit lanes
//! - **Rounds**: 24, each composed of (θ, ρ, π, χ, ι)
//! - **θ**: XORs each lane with parity of two neighbouring columns
//! - **ρ**: rotates each lane by a fixed offset (see [`RHO_OFFSETS`])
//! - **π**: permutes lane positions (see [`PI_LANE_INDICES`])
//! - **χ**: non-linear `lane[x] ^= !lane[x+1] & lane[x+2]` per row
//! - **ι**: XORs round constant into lane (0,0) (see [`ROUND_CONSTANTS`])
//!
//! # AIR strategy
//!
//! Each Keccak round occupies a contiguous block of rows.  Within a
//! round, sub-steps are sequenced: one row range per (θ, ρ, π, χ, ι)
//! sub-step.  Bitwise operations are expressed by decomposing each
//! 64-bit lane into 64 boolean cells; the constraint set enforces:
//!
//! 1. **Booleanity**: every bit cell `b` satisfies `b · (b − 1) = 0`
//! 2. **XOR**: `c = a XOR b` ⇔ `c = a + b − 2·a·b` (boolean inputs)
//! 3. **AND**: `c = a AND b` ⇔ `c = a · b` (boolean inputs)
//! 4. **NOT**: `c = NOT a` ⇔ `c = 1 − a` (boolean input)
//!
//! Lane reconstruction at sub-step boundaries packs bits back into a
//! field element via `lane = Σ bᵢ · 2ⁱ` for `i ∈ [0..64)`.

/// SHA-3 variants the wrapper supports.  Maps to the inner proof's
/// FIPS-202 hash variant for the corresponding NIST PQ level.
///
/// Sponge parameters (FIPS 202 §6.1):
/// - SHA3-256: rate r = 1088 bits, capacity c = 512 bits, output 256 bits
/// - SHA3-384: rate r =  832 bits, capacity c = 768 bits, output 384 bits
/// - SHA3-512: rate r =  576 bits, capacity c =1024 bits, output 512 bits
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Sha3Variant {
    Sha3_256,
    Sha3_384,
    Sha3_512,
}

impl Sha3Variant {
    /// Sponge rate `r` in bits.  Block size is `r` bits = `r / 8` bytes.
    pub const fn rate_bits(self) -> usize {
        match self {
            Self::Sha3_256 => 1088,
            Self::Sha3_384 => 832,
            Self::Sha3_512 => 576,
        }
    }

    /// Sponge capacity `c` in bits.  `r + c = 1600` for all Keccak-f1600
    /// variants.  Capacity caps the effective collision entropy (paper
    /// Theorem 8 / Corollary 2).
    pub const fn capacity_bits(self) -> usize {
        1600 - self.rate_bits()
    }

    /// Output length in bits.
    pub const fn output_bits(self) -> usize {
        match self {
            Self::Sha3_256 => 256,
            Self::Sha3_384 => 384,
            Self::Sha3_512 => 512,
        }
    }

    /// Block size in bytes (= rate / 8).
    pub const fn block_bytes(self) -> usize {
        self.rate_bits() / 8
    }

    /// Output length in bytes.
    pub const fn output_bytes(self) -> usize {
        self.output_bits() / 8
    }

    /// The NIST PQ level this variant pairs with by default.
    /// L1 ↔ SHA3-256, L3 ↔ SHA3-384, L5 ↔ SHA3-512 (paper Table 2).
    pub const fn default_for_level(nist_level: u8) -> Self {
        match nist_level {
            1 => Self::Sha3_256,
            3 => Self::Sha3_384,
            5 => Self::Sha3_512,
            _ => panic!("Sha3Variant: unsupported NIST level"),
        }
    }
}

