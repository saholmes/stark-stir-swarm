    #[test]
    fn rho_offsets_well_formed() {
        // FIPS 202 §3.2.2 Table 1: exactly one offset is 0 (lane (0, 0));
        // remaining 24 offsets are distinct mod 64.
        assert_eq!(RHO_OFFSETS.len(), 25);
        assert_eq!(RHO_OFFSETS[0], 0);
        let mut nonzero: Vec<u32> = RHO_OFFSETS.iter().filter(|&&o| o != 0).copied().collect();
        nonzero.sort();
        nonzero.dedup();
        assert_eq!(nonzero.len(), 24, "ρ offsets must be 24 distinct non-zero values");
        // All offsets are < 64.
        assert!(RHO_OFFSETS.iter().all(|&o| o < 64));
    }

    #[test]
    fn pi_lane_indices_is_permutation() {
        // π is a permutation of {0..25}.
        assert_eq!(PI_LANE_INDICES.len(), 25);
        let mut sorted: Vec<usize> = PI_LANE_INDICES.to_vec();
        sorted.sort();
        for i in 0..25 {
            assert_eq!(sorted[i], i, "PI_LANE_INDICES is not a permutation");
        }
    }

