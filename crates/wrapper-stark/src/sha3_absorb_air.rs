/// Per-lane rotation offsets used by the ρ step (FIPS 202 §3.2.2 Table 1).
/// Indexed as `RHO_OFFSETS[5*y + x]` where `(x, y) ∈ [0..5)²`.
/// Offsets are mod 64.
pub const RHO_OFFSETS: [u32; 25] = [
    // y = 0
     0,  1, 62, 28, 27,
    // y = 1
    36, 44,  6, 55, 20,
    // y = 2
     3, 10, 43, 25, 39,
    // y = 3
    41, 45, 15, 21,  8,
    // y = 4
    18,  2, 61, 56, 14,
];

/// Lane index permutation used by the π step (FIPS 202 §3.2.3).
/// After π, lane at position `(x, y)` comes from the lane previously
/// at position `(x + 3·y mod 5, x)`.  We pre-compute the source index
/// for each destination as `5·y + x → 5·x + (x + 3·y mod 5)`.
pub const PI_LANE_INDICES: [usize; 25] = {
    let mut out = [0usize; 25];
    let mut i = 0;
    while i < 25 {
        let x = i % 5;
        let y = i / 5;
        // π maps (x, y) → (y, 2x + 3y mod 5).
        // Equivalently, destination (x', y') reads from source
        // (x_src, y_src) = (y', x'+3y' mod 5).
        let x_src = y;
        let y_src = (2 * x + 3 * y) % 5;
        out[5 * y_src + x_src] = i;  // canonical π destination → source mapping
        i += 1;
    }
    out
};

/// Sub-steps of one Keccak round, in execution order within a row range.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum RoundStep {
    /// Compute column parities `C[x] = ⊕_y A[x, y]` and apply
    /// `A[x, y] ⊕= C[x-1] ⊕ ROTL1(C[x+1])`.
    Theta,
    /// Per-lane rotation by [`RHO_OFFSETS`].
    Rho,
    /// Lane index permutation by [`PI_LANE_INDICES`].
    Pi,
    /// Non-linear `A[x, y] ⊕= !A[x+1, y] & A[x+2, y]` per row.
    Chi,
    /// XOR round constant into lane (0, 0).
    Iota,
}

impl RoundStep {
    pub const ALL: [RoundStep; 5] = [
        RoundStep::Theta, RoundStep::Rho, RoundStep::Pi,
        RoundStep::Chi, RoundStep::Iota,
    ];
}

/// Native Keccak-f1600 state: 25 lanes of 64 bits.  Used as the
/// reference oracle for AIR-side correctness checks during testing.
pub type KeccakState = [u64; 25];

/// Column layout for the SHA-3 absorb sub-AIR.
///
/// Within each round-row block, columns are organised as:
/// - 25 lanes × 64 boolean cells = 1 600 bit cells (state representation)
/// - 25 column-parity cells (θ helper)
/// - 25 rotated-lane cells (ρ output)
/// - 25 permuted-lane cells (π output)
/// - 25 χ-output cells (one per lane after non-linear step)
/// - 1 round-constant cell (ι input from [`ROUND_CONSTANTS`])
/// - 5 sub-step selector cells (one per [`RoundStep`])
#[derive(Clone, Debug)]
pub struct AbsorbAirLayout {
    pub variant: Sha3Variant,
    /// Trace width: per-step bit-decomposed cells + helpers + selectors.
    pub width: usize,
    /// Rows per single Keccak-f1600 permutation (= 24 rounds × 5 steps).
    pub rows_per_permutation: usize,
    /// Rows for a complete absorb of one input block (= 1 absorb XOR + 1 permutation).
    pub rows_per_absorb_block: usize,
    /// Number of input blocks the layout is sized for (caller-provided).
    pub n_blocks: usize,
}

impl AbsorbAirLayout {
    /// Build a layout sized for absorbing `n_blocks` input blocks using
    /// `variant`.  Production blocks pack `variant.block_bytes()` bytes
    /// each before zero-padding the final block.
    pub fn new(variant: Sha3Variant, n_blocks: usize) -> Self {
        let rows_per_permutation = 24 * RoundStep::ALL.len();  // 24 × 5 = 120
        let rows_per_absorb_block = rows_per_permutation + 1;   // +1 for the XOR-in row
        // Width: 1600 state bits + 25 parity + 25 rotated + 25 permuted
        // + 25 chi-out + 1 round constant + 5 selectors.  Each bit is a
        // boolean cell, parity/rotated/permuted/chi cells are 64-bit
        // lanes encoded as a single field element each.
        let width = 1600 /* state bits */
                  + 25 * 4 /* parity + rotated + permuted + chi-out lanes */
                  + 1     /* round constant lane */
                  + 5;    /* sub-step selectors */
        Self { variant, width, rows_per_permutation, rows_per_absorb_block, n_blocks }
    }

    /// Total rows required for the absorb sequence (sum across blocks).
    pub fn total_rows(&self) -> usize {
        self.rows_per_absorb_block * self.n_blocks
    }
}

